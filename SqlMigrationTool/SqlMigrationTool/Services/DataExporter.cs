using System.Text.Json;
using Microsoft.Data.SqlClient;
using SqlMigrationTool.Models;

namespace SqlMigrationTool.Services;

public class DataExporter
{
    private readonly ConnectionConfig _cfg;

    private static readonly JsonSerializerOptions _jsonOptions = new()
    {
        WriteIndented = false
    };

    public DataExporter(ConnectionConfig cfg) => _cfg = cfg;

    /// <summary>
    /// Streams the table in a single pass and writes a data_NNN.json file every
    /// <paramref name="chunkSize"/> rows, so each row is exported exactly once
    /// (OFFSET paging without a stable order could skip or repeat rows).
    /// </summary>
    public async Task<List<(string filePath, int rows)>> ExportTableAsync(
        DatabaseObject    table,
        string            outputDir,
        int               chunkSize,
        IProgress<string> progress,
        CancellationToken ct)
    {
        var results = new List<(string, int)>();
        Directory.CreateDirectory(outputDir);

        var columns = await GetColumnNamesAsync(table, ct);
        if (columns.Count == 0) return results;

        var colSelect = string.Join(", ", columns.Select(c => SqlNames.Quote(c)));
        var sql = $"SELECT {colSelect} FROM {SqlNames.Quote(table.Schema, table.Name)}";

        await using var conn = await SqlConnectionService.OpenAsync(_cfg);
        await using var cmd  = new SqlCommand(sql, conn) { CommandTimeout = 0 };
        await using var rdr  = await cmd.ExecuteReaderAsync(System.Data.CommandBehavior.SequentialAccess, ct);

        var rows  = new List<object?[]>(chunkSize);
        int chunk = 1;

        async Task FlushAsync()
        {
            var filePath = Path.Combine(outputDir, $"data_{chunk:D3}.json");
            var chunkObj = new DataChunk
            {
                Table   = table.FullName,
                Chunk   = chunk,
                Columns = columns,
                Rows    = rows
            };
            await File.WriteAllTextAsync(filePath, JsonSerializer.Serialize(chunkObj, _jsonOptions), ct);

            progress.Report($"  {table.FullName} → chunk {chunk} ({rows.Count:N0} rows)");
            results.Add((filePath, rows.Count));
            rows = new List<object?[]>(chunkSize);
            chunk++;
        }

        while (await rdr.ReadAsync(ct))
        {
            rows.Add(ReadRow(rdr));
            if (rows.Count == chunkSize)
                await FlushAsync();
        }
        if (rows.Count > 0)
            await FlushAsync();

        return results;
    }

    /// <summary>
    /// Columns whose values are exported: everything except computed columns
    /// (recalculated on insert) and rowversion/timestamp (generated by the server
    /// and cannot be inserted).
    /// </summary>
    private async Task<List<string>> GetColumnNamesAsync(DatabaseObject table, CancellationToken ct)
    {
        const string sql = @"
            SELECT c.name
            FROM sys.columns c
            WHERE c.object_id = OBJECT_ID(@fqn)
              AND c.is_computed = 0
              AND TYPE_NAME(c.system_type_id) <> 'timestamp'
            ORDER BY c.column_id";

        await using var conn = await SqlConnectionService.OpenAsync(_cfg);
        await using var cmd  = new SqlCommand(sql, conn) { CommandTimeout = 60 };
        cmd.Parameters.AddWithValue("@fqn", SqlNames.Quote(table.Schema, table.Name));

        var cols = new List<string>();
        await using var rdr = await cmd.ExecuteReaderAsync(ct);
        while (await rdr.ReadAsync(ct)) cols.Add(rdr.GetString(0));
        return cols;
    }

    private static object?[] ReadRow(SqlDataReader rdr)
    {
        var row = new object?[rdr.FieldCount];
        for (int i = 0; i < row.Length; i++)
        {
            if (rdr.IsDBNull(i))
            {
                row[i] = null;
                continue;
            }

            var val = rdr.GetValue(i);
            row[i] = val switch
            {
                byte[]   bytes => Convert.ToBase64String(bytes),
                DateTime dt    => dt.ToString("O"),
                DateOnly d     => d.ToString("yyyy-MM-dd"),
                TimeOnly t     => t.ToString("HH:mm:ss.fffffff"),
                TimeSpan ts    => ts.ToString("c"),
                Guid g         => g.ToString(),
                _              => val
            };
        }
        return row;
    }
}
